class Solution {
public:
    long long countCommas(long long n) {
        long long ans=0;
        if(n<1000){
            ans=0;
        }
        if(n>=1000 && n<1000000){
            ans=n-1000+1;
        }
        if(n>=1000000 && n<1000000000){
            ans=1000000-1000 + 2*(n-1000000+1);
        }
        if(n>=1000000000 && n<1000000000000){
            ans=1000000-1000 + 2*(1000000000-1000000) + 3*(n-1000000000+1);
        }
        if(n>=1000000000000 && n<1000000000000000){
            ans=1000000-1000 + 2*(1000000000-1000000) + 3*(1000000000000-1000000000) + 4*(n-1000000000000+1);
        }
        if(n==1000000000000000){
            ans=1000000-1000 + 2*(1000000000-1000000) + 3*(1000000000000-1000000000) + 4*(1000000000000000-1000000000000) + 5*(n-1000000000000000+1);

        }
        return ans;
    }
};